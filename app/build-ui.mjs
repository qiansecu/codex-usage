import fs from 'node:fs';
import { createHeader } from './header-controller.mjs';

const read = name => fs.readFileSync(new URL(name, import.meta.url), 'utf8').replace(/^\uFEFF/, '').trim();
const footer = read('./footer-controller.js');
const header = `if (typeof window.electronBridge?.sendMessageFromView === 'function') (${createHeader.toString()})({ window, document, location });`;
// Keep one atomic payload for the existing injector's source-change hot reload.
const payload = `// Generated by build-ui.mjs. Edit the two controller source files.\n(() => {\nconst footerResult = ${footer}\nif (footerResult?.state !== 'installed') return footerResult;\n${header}\nreturn window.__codexUsageLayoutProbeV1?.status();\n})();\n`;
const output = new URL('./footer-page.js', import.meta.url);
const temporary = new URL('./footer-page.js.tmp', import.meta.url);
if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--check')) throw new Error('Usage: node build-ui.mjs [--check]');
if (process.argv[2] === '--check') {
  if (fs.readFileSync(output, 'utf8') !== payload) throw new Error('UI payload is out of date. Run node build-ui.mjs first.');
} else {
  fs.writeFileSync(temporary, payload, 'utf8');
  fs.renameSync(temporary, output);
}
